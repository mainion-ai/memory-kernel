/**
 * cron-template — pure generator for the canonical memory-sync wrapper (#143).
 *
 * `mk init --cron` calls into here. Keeping generation pure (no FS, no
 * Date.now) lets us snapshot-test it deterministically and lets the CLI layer
 * own crontab/file-system side effects.
 *
 * The generated script embeds machine-parseable `# mk:KEY=VALUE` header lines
 * so `mk init --cron --update` can re-read the original paths without making
 * the user re-type them, and `mk doctor` (#140) can detect wrapper-vs-binary
 * version drift.
 */

import path from 'path';

export interface CronWrapperOptions {
  /** Absolute path to the memory directory. */
  memoryDir: string;
  /** Absolute path the rendered CLAUDE.md should be written to. */
  claudeMd: string;
  /** Absolute path to the git repo to commit/push from. Defaults to dirname(memoryDir). */
  memoryRepo?: string;
  /** Token budget passed to `mk render --max-tokens`. Default 16000. */
  maxTokens?: number;
  /**
   * Agent ID passed to `mk reflect --agent-id`. When omitted the generated
   * script uses `$(hostname -s)` so the same script works across hosts.
   */
  agentId?: string;
  /** Kernel version string for the header, e.g. `1.19.3`. */
  kernelVersion: string;
  /**
   * ISO-8601 timestamp for the header. Injected (not generated internally)
   * so snapshot tests stay deterministic.
   */
  generatedAt: string;
}

/** Prefix used for machine-parseable header lines. */
const HEADER_PREFIX = '# mk:';

/** Default render token budget — matches mk render's own default. */
export const DEFAULT_MAX_TOKENS = 16000;

interface MachineHeader {
  generatorVersion: string;
  generatedAt: string;
  memoryDir: string;
  claudeMd: string;
  memoryRepo: string;
  maxTokens: number;
  agentId: string | null; // null means "use $(hostname -s) at run time"
}

function resolveDefaults(opts: CronWrapperOptions): MachineHeader {
  return {
    generatorVersion: opts.kernelVersion,
    generatedAt: opts.generatedAt,
    memoryDir: opts.memoryDir,
    claudeMd: opts.claudeMd,
    memoryRepo: opts.memoryRepo ?? path.dirname(opts.memoryDir),
    maxTokens: opts.maxTokens ?? DEFAULT_MAX_TOKENS,
    agentId: opts.agentId ?? null,
  };
}

/**
 * Generate the canonical wrapper script. Returns the full file contents
 * including shebang and trailing newline. Caller is responsible for writing
 * to disk and chmod +x.
 */
export function generateCronWrapper(opts: CronWrapperOptions): string {
  validate(opts);
  const h = resolveDefaults(opts);

  const headerLines = [
    '#!/usr/bin/env bash',
    `# Canonical memory-sync wrapper for memory-kernel.`,
    `# Generated by mk v${h.generatorVersion}.`,
    `# Regenerate in place with: mk init --cron --update --output <this-file>`,
    `# Do not edit the "${HEADER_PREFIX}" lines below — they are read by mk doctor.`,
    `${HEADER_PREFIX}generator-version=${h.generatorVersion}`,
    `${HEADER_PREFIX}generated-at=${h.generatedAt}`,
    `${HEADER_PREFIX}memory-dir=${h.memoryDir}`,
    `${HEADER_PREFIX}claude-md=${h.claudeMd}`,
    `${HEADER_PREFIX}memory-repo=${h.memoryRepo}`,
    `${HEADER_PREFIX}max-tokens=${h.maxTokens}`,
    `${HEADER_PREFIX}agent-id=${h.agentId ?? '$(hostname -s)'}`,
  ];

  const body = [
    '',
    'set -euo pipefail',
    '',
    '# Paths — embedded by mk init --cron. Override at runtime by exporting',
    '# the matching MK_* env var (useful for testing without regenerating).',
    `MEMORY_DIR="${'$'}{MK_MEMORY_DIR:-${h.memoryDir}}"`,
    `CLAUDE_MD="${'$'}{MK_CLAUDE_MD:-${h.claudeMd}}"`,
    `MEMORY_REPO="${'$'}{MK_MEMORY_REPO:-${h.memoryRepo}}"`,
    `MAX_TOKENS="${'$'}{MK_MAX_TOKENS:-${h.maxTokens}}"`,
    h.agentId
      ? `AGENT_ID="${'$'}{MK_AGENT_ID:-${h.agentId}}"`
      : `AGENT_ID="${'$'}{MK_AGENT_ID:-$(hostname -s)}"`,
    `SESSION_ID="sync-$(date -u +%Y%m%dT%H%M%SZ)"`,
    '',
    '# Step 1: consolidate (dedup, TTL, promote, detect conflicts).',
    'mk reflect -d "$MEMORY_DIR" --agent-id "$AGENT_ID" --session-id "$SESSION_ID"',
    '',
    '# Step 2: render CLAUDE.md from active atoms.',
    'mk render -d "$MEMORY_DIR" -o "$CLAUDE_MD" --max-tokens "$MAX_TOKENS"',
    '',
    '# Step 3: commit + push if the rendered output (or any tracked file) changed.',
    '#',
    '# git add -A picks up every untracked file under MEMORY_REPO. If this',
    '# wrapper script itself lives inside MEMORY_REPO, add its filename to',
    '# .gitignore so it does not get committed alongside the memory data.',
    'cd "$MEMORY_REPO"',
    'if [ -n "$(git status --porcelain)" ]; then',
    '  git add -A',
    '  git commit -m "memory: sync $(date -u +%Y-%m-%dT%H:%MZ)"',
    '  git push',
    'else',
    '  echo "memory-sync: no changes to commit"',
    'fi',
    '',
  ];

  return [...headerLines, ...body].join('\n');
}

function validate(opts: CronWrapperOptions): void {
  if (!path.isAbsolute(opts.memoryDir)) {
    throw new Error(`memoryDir must be an absolute path (got: ${opts.memoryDir})`);
  }
  if (!path.isAbsolute(opts.claudeMd)) {
    throw new Error(`claudeMd must be an absolute path (got: ${opts.claudeMd})`);
  }
  if (opts.memoryRepo !== undefined && !path.isAbsolute(opts.memoryRepo)) {
    throw new Error(`memoryRepo must be an absolute path (got: ${opts.memoryRepo})`);
  }
  if (opts.maxTokens !== undefined && (!Number.isInteger(opts.maxTokens) || opts.maxTokens <= 0)) {
    throw new Error(`maxTokens must be a positive integer (got: ${opts.maxTokens})`);
  }
  if (!/^[\d.]+/.test(opts.kernelVersion)) {
    throw new Error(`kernelVersion looks malformed: ${opts.kernelVersion}`);
  }
  if (Number.isNaN(Date.parse(opts.generatedAt))) {
    throw new Error(`generatedAt must be a parseable ISO timestamp (got: ${opts.generatedAt})`);
  }
}

/**
 * Parse the machine-readable `# mk:KEY=VALUE` header lines out of a generated
 * wrapper script. Used by `mk init --cron --update` to recover the original
 * paths so the user doesn't have to retype them.
 *
 * Tolerant of files that aren't mk-generated — returns null if no header
 * found. Stops at the first non-blank, non-comment line so it doesn't pick
 * up `# mk:` strings embedded later in the script body.
 */
export function parseGeneratedHeader(content: string): MachineHeader | null {
  const found: Partial<Record<string, string>> = {};

  for (const rawLine of content.split('\n')) {
    const line = rawLine.trim();
    if (line === '' || line.startsWith('#!')) continue;
    if (!line.startsWith('#')) break;
    if (!line.startsWith(HEADER_PREFIX)) continue;
    const rest = line.slice(HEADER_PREFIX.length);
    const eq = rest.indexOf('=');
    if (eq < 0) continue;
    found[rest.slice(0, eq).trim()] = rest.slice(eq + 1).trim();
  }

  if (
    !found['generator-version']
    || !found['memory-dir']
    || !found['claude-md']
  ) {
    return null;
  }

  const maxTokens = found['max-tokens'] ? parseInt(found['max-tokens'], 10) : DEFAULT_MAX_TOKENS;
  const agentIdRaw = found['agent-id'] ?? '';
  // `$(hostname -s)` sentinel means "no fixed agent ID" — preserve that.
  const agentId = agentIdRaw && agentIdRaw !== '$(hostname -s)' ? agentIdRaw : null;

  return {
    generatorVersion: found['generator-version'],
    generatedAt: found['generated-at'] ?? '',
    memoryDir: found['memory-dir'],
    claudeMd: found['claude-md'],
    memoryRepo: found['memory-repo'] ?? path.dirname(found['memory-dir']),
    maxTokens: Number.isInteger(maxTokens) && maxTokens > 0 ? maxTokens : DEFAULT_MAX_TOKENS,
    agentId,
  };
}

/**
 * Idempotently append a crontab line to a file. If a line referencing the
 * same target script already exists, replace it instead of appending a
 * duplicate. Returns the final contents — caller writes back via
 * `crontab -` (or, in tests, against a temp file via the MK_CRONTAB_FILE
 * override that the CLI consults).
 *
 * Pure function: takes the current crontab text + the new line, returns
 * new text. Identifies "the same entry" by a whole-token match of the
 * target script path — the path must appear bounded by characters that
 * cannot belong to a filesystem path (whitespace, quotes, line ends).
 * A trailing `.bak`, `-disabled`, or any path-continuation suffix means
 * it's a different script and is left alone.
 */
export function applyCrontabLine(
  current: string,
  scheduleAndScript: string,
  scriptPath: string,
): string {
  const lines = current.split('\n');
  let replaced = false;
  const next: string[] = [];
  const scriptTokenRe = scriptPathTokenRegex(scriptPath);

  for (const line of lines) {
    // If a non-comment line contains the script path as a whole shell token,
    // treat it as the existing entry and replace it. Avoids duplicate entries
    // when --install-cron is run twice with the same --output, but does not
    // clobber siblings like `.../sync.sh.bak` whose path is a strict superset.
    if (
      line.trim() !== ''
      && !line.trim().startsWith('#')
      && scriptTokenRe.test(line)
    ) {
      if (!replaced) {
        next.push(scheduleAndScript);
        replaced = true;
      }
      continue;
    }
    next.push(line);
  }

  if (!replaced) {
    // Append before any trailing blank line for tidiness.
    while (next.length > 0 && next[next.length - 1] === '') next.pop();
    next.push(scheduleAndScript);
    next.push('');
  }

  return next.join('\n');
}

/**
 * Build a regex that matches `scriptPath` only when it appears as a whole
 * shell token — i.e. not adjacent on either side to characters that could
 * legitimately extend the path (`[A-Za-z0-9._/-]`). This is the boundary
 * rule we want for crontab lines: `/p/sync.sh` matches in
 * `* * * * * /p/sync.sh`, `"/p/sync.sh"`, and `/p/sync.sh --arg`, but not
 * in `/p/sync.sh.bak` or `/p/sync.sh-disabled`.
 */
function scriptPathTokenRegex(scriptPath: string): RegExp {
  const escaped = scriptPath.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![A-Za-z0-9._/\\-])${escaped}(?![A-Za-z0-9._/\\-])`);
}
